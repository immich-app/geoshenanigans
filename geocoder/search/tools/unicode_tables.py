#!/usr/bin/python3 -I
"""Writes src/text/unicode.rs: the Unicode character classes Nominatim's normaliser reads that Rust's
standard library has no test for, from this Python's unicodedata.

usage: unicode_tables.py > src/text/unicode.rs
"""
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, doc, items):
    print(f'/// {doc}')
    print(f'pub const {name}: &[(u32, u32)] = &[')
    for i in range(0, len(items), 6):
        print('    ' + ' '.join(f'(0x{a:X}, 0x{b:X}),' for a, b in items[i:i + 6]))
    print('];')
    print()


def main():
    cat = unicodedata.category
    print(f'//! Generated by tools/unicode_tables.py from Unicode {unicodedata.unidata_version}: do not edit.')
    print('//! Each table is sorted, its ranges inclusive and apart.')
    print()
    table('PUNCTUATION_OR_SYMBOL', 'General category P* or S*.', ranges(lambda c: cat(c)[0] in 'PS'))
    table('MODIFIER_LETTER', 'General category Lm.', ranges(lambda c: cat(c) == 'Lm'))
    table('NONSPACING_MARK_OR_FORMAT', 'General category Mn or Cf.', ranges(lambda c: cat(c) in ('Mn', 'Cf')))
    table('SPACING_VIRAMA', 'Canonical combining class 9 (virama), other than Mn.',
          ranges(lambda c: unicodedata.combining(c) == 9 and cat(c) != 'Mn'))
    zeros = [cp for cp in range(0x110000) if cat(chr(cp)) == 'Nd' and unicodedata.decimal(chr(cp)) == 0]
    for z in zeros:
        assert all(unicodedata.decimal(chr(z + i), None) == i for i in range(10)), hex(z)
    print('/// The zero of each run of ten decimal digits (general category Nd), ascending.')
    print('pub const DECIMAL_ZEROS: &[u32] = &[')
    for i in range(0, len(zeros), 10):
        print('    ' + ' '.join(f'0x{z:X},' for z in zeros[i:i + 10]))
    print('];')


if __name__ == '__main__':
    main()
