#!/usr/bin/python3 -I
"""Writes src/text/latin_ascii.rs: how Nominatim's transliteration spells each Latin letter it does
not spell as NFKD without marks would, read from the behaviour of a Nominatim database's ICU rules.

usage: latin_ascii.py DSN > src/text/latin_ascii.rs
DSN: a libpq connection string of a Nominatim database (its nominatim_properties hold the rules).
Needs PyICU and psycopg.
"""
import sys
import unicodedata

import psycopg
from icu import Transliterator

# The Unicode blocks of the Latin script that hold letters NFKC does not fold into ASCII.
LATIN = [(0x00C0, 0x024F), (0x0250, 0x02AF), (0x1D00, 0x1DBF), (0x1E00, 0x1EFF), (0x2C60, 0x2C7F),
         (0xA720, 0xA7FF), (0xAB30, 0xAB6F), (0x10780, 0x107BF), (0x1DF00, 0x1DFFF)]


def main():
    with psycopg.connect(sys.argv[1]) as conn:
        props = dict(conn.execute("SELECT property, value FROM nominatim_properties WHERE property IN "
                                  "('tokenizer_import_normalisation', 'tokenizer_import_transliteration')")
                     .fetchall())
    norm = Transliterator.createFromRules('normalization', props['tokenizer_import_normalisation'])
    trans = Transliterator.createFromRules('transliteration', props['tokenizer_import_transliteration'])
    spelt = {}
    for lo, hi in LATIN:
        for cp in range(lo, hi + 1):
            if unicodedata.category(chr(cp)) not in ('Ll', 'Lu', 'Lt', 'Lo'):
                continue
            for c in norm.transliterate(chr(cp)).strip():
                if not unicodedata.category(c).startswith('L'):
                    continue
                fold = ''.join(x for x in unicodedata.normalize('NFKD', c) if not unicodedata.combining(x))
                out = trans.transliterate(c).strip()
                if out != (fold if fold.isascii() else ''):
                    spelt[c] = out
    print('//! Generated by tools/latin_ascii.py from the behaviour of Nominatim\'s transliteration: do not')
    print('//! edit. A Latin letter not named here is spelt as NFKD without marks leaves it when that is')
    print('//! ASCII, and dropped otherwise.')
    print()
    print('/// The blocks of the Latin script, inclusive.')
    print('pub const LATIN_SCRIPT: &[(u32, u32)] = &[')
    for i in range(0, len(LATIN), 6):
        print('    ' + ' '.join(f'(0x{a:X}, 0x{b:X}),' for a, b in LATIN[i:i + 6]))
    print('];')
    print()
    print('/// A lower-case Latin letter and its ASCII spelling, by letter.')
    print('pub const LATIN_ASCII: &[(char, &str)] = &[')
    items = sorted(spelt.items())
    for i in range(0, len(items), 6):
        print('    ' + ' '.join(f"('{c}', \"{s}\")," for c, s in items[i:i + 6]))
    print('];')


if __name__ == '__main__':
    main()
