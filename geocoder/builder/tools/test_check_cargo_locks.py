#!/usr/bin/env python3
"""Tests for check_cargo_locks.py. Run: python3 -m unittest discover -s geocoder/builder/tools"""
import io
import os
import re
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stdout

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import check_cargo_locks as sut  # noqa: E402

GEOCODER = os.path.join(HERE, "..", "..")
WORKFLOWS = os.path.join(GEOCODER, "..", ".github", "workflows")
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"


def lock(*packages):
    """A Cargo.lock of `packages`, each (name, version) from crates.io or (name, version, None), a
    path package."""
    out = ["# This file is automatically @generated by Cargo.", "version = 4", ""]
    for name, version, *path in packages:
        out += ["[[package]]", f'name = "{name}"', f'version = "{version}"']
        if not path:
            out += [f'source = "{REGISTRY}"', 'checksum = "00"']
        out.append("")
    return "\n".join(out)


class CheckCargoLocksTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def write(self, name, text):
        path = os.path.join(self.tmp.name, name)
        with open(path, "w") as f:
            f.write(text)
        return path

    def check(self, base, *others):
        out = io.StringIO()
        with redirect_stdout(out):
            code = sut.main([self.write("base.lock", base)] + [self.write(f"other{i}.lock", o) for i, o in enumerate(others)])
        return code, out.getvalue()

    def test_a_lock_whose_every_package_the_base_holds_alike_agrees(self):
        base = lock(("tokio", "1.54.1"), ("hyper", "1.8.1"), ("windows-sys", "0.52.0"), ("windows-sys", "0.59.0"),
                    ("query-server", "0.1.0", None))
        other = lock(("tokio", "1.54.1"), ("windows-sys", "0.59.0"), ("query-server", "0.1.0", None))

        self.assertEqual(self.check(base, other), (0, ""))

    def test_a_package_at_another_version_than_the_bases_is_named(self):
        base = lock(("tokio", "1.54.1"), ("hyper", "1.8.1"))
        other = lock(("tokio", "1.53.3"), ("hyper", "1.8.1"))

        code, out = self.check(base, other)

        self.assertEqual(code, 1)
        self.assertIn("tokio 1.53.3", out)
        self.assertIn("1.54.1", out)
        self.assertNotIn("hyper", out)

    def test_a_package_the_base_lacks_is_named(self):
        base = lock(("tokio", "1.54.1"))
        other = lock(("tokio", "1.54.1"), ("fst", "0.4.7"))

        code, out = self.check(base, other)

        self.assertEqual(code, 1)
        self.assertIn("fst 0.4.7", out)

    def test_a_package_of_another_source_is_named(self):
        base = lock(("tokio", "1.54.1"))
        other = lock(("tokio", "1.54.1", None))

        code, out = self.check(base, other)

        self.assertEqual(code, 1)
        self.assertIn("tokio 1.54.1", out)

    def test_each_lock_after_the_base_is_checked(self):
        base = lock(("tokio", "1.54.1"))

        code, out = self.check(base, lock(("tokio", "1.54.1")), lock(("tokio", "1.50.0")))

        self.assertEqual(code, 1)
        self.assertIn("other1.lock", out)
        self.assertNotIn("other0.lock", out)

    # query-portal, a bin of place-search, is built with search/Cargo.lock; its sources are tested in
    # query-server's tests, with server/Cargo.lock: the two agree, and CI checks that they do.
    def test_the_portals_lock_agrees_with_the_one_its_tests_run_with(self):
        server, search = (os.path.join(GEOCODER, d, "Cargo.lock") for d in ("server", "search"))

        self.assertEqual(self.check(open(server).read(), open(search).read()), (0, ""))
        with open(os.path.join(WORKFLOWS, "geocoder-tests.yml")) as f:
            steps = f.read()
        self.assertRegex(steps, r"(?m)^ +run: python3 geocoder/builder/tools/check_cargo_locks\.py geocoder/server/Cargo\.lock "
                                r"geocoder/search/Cargo\.lock$")

    def test_it_runs_as_a_script(self):
        base = self.write("base.lock", lock(("tokio", "1.54.1")))
        other = self.write("other.lock", lock(("tokio", "1.53.3")))

        run = subprocess.run([sys.executable, os.path.join(HERE, "check_cargo_locks.py"), base, other], capture_output=True, text=True)

        self.assertEqual(run.returncode, 1)
        self.assertTrue(re.search(r"tokio 1\.53\.3", run.stdout), run.stdout)


if __name__ == "__main__":
    unittest.main()
